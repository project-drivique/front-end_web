export function obtenerEstadoVisible(estado) {
  if (!estado) return null
  const estadoNormalizado = String(estado).trim().toUpperCase()
  return ESTADO_VISIBLE_RESERVA[estadoNormalizado] || estadoNormalizado.toLowerCase()
}
